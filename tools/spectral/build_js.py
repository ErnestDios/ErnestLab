#!/usr/bin/env python3
"""Regenerate js/03-measured.js: every number in Ernest Lab that comes from measured data.

    pip install colour-science scipy
    python3 tools/spectral/build_js.py            # uses the cached noise table
    python3 tools/spectral/build_js.py --noise    # also re-measures the noise table (~5 min)
"""
import io, os, sys, contextlib, subprocess
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import bw_weights, grain_calib

def grab(fn):
    b = io.StringIO()
    with contextlib.redirect_stdout(b): fn()
    return b.getvalue().strip()

ap = os.path.join(HERE, "data", "grain_ap.js.txt")
if "--noise" in sys.argv:
    open(ap, "w").write(subprocess.run([sys.executable, os.path.join(HERE, "noise_table.py")], capture_output=True, text=True, check=True).stdout)
out = f"""/* Ernest Lab · js/03-measured.js · GENERATED by tools/spectral/build_js.py — do not edit by hand.
   Everything here is computed from measured data (see tools/spectral/ and its README for sources, method and checks):
   BW_W       black & white weights per film × filter, from datasheet spectral sensitivities and filter transmissions
   GRAIN_DATA datasheet RMS granularity per stock and layer, as an exposure wobble in stops around mid grey
   GAUGES     gate widths of common film formats (mm)
   GRAIN_AP   statistics of the app's own grain noise, to hit a datasheet granularity at any resolution
   Classic script (not a module): loads before js/03-params.js and shares one global scope. */
"use strict";
{grab(bw_weights.js)}

{grab(grain_calib.js)}

{open(ap).read().strip()}
"""
open(os.path.join(ROOT, "js", "03-measured.js"), "w").write(out)
print("wrote js/03-measured.js", len(out), "bytes")
