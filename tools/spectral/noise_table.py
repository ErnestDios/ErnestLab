"""Tabulate the aperture-averaged standard deviation of Ernest Lab's grain noise (unit amplitude).

    python3 tools/spectral/noise_table.py      # prints the GRAIN_AP table for js/05-gl.js

T[rough][cell][D] = std of gn() averaged over a disk of D px, for noise cells of `cell` px; D = 1 is a single
pixel. Two seeds averaged. The renderer interpolates it (log-space, trilinear) to turn a datasheet granularity
(σ at a 48 µm aperture) into the per-pixel amplitude for any resolution, gauge and grain size.
"""
import sys, os; sys.path.insert(0, os.path.dirname(__file__))
import numpy as np
from noise_stats import field, disk_avg_std
ROUGH = [0, 0.25, 0.5, 0.75, 1.0]
CELL = [0.35, 0.5, 0.7, 1.0, 1.4, 2.0, 2.8, 4.0, 5.6, 8.0, 11.3, 16.0]
DIAM = [1, 2, 3, 4, 6, 8, 12, 16, 24, 32, 48, 64]
T = []
for r in ROUGH:
    row = []
    for c in CELL:
        N = 1024 if c <= 2.8 else 2048
        vals = []
        for seed in (7, 19):
            f = field(N, c, r, seed)
            vals.append([f.std() if D == 1 else disk_avg_std(f, D) for D in DIAM])
        row.append(np.mean(vals, axis=0))
    T.append(row)
    print(f"# rough {r} done", file=sys.stderr)
T = np.array(T)
print("/* generated by tools/spectral/noise_table.py: std of the grain noise averaged over a disk of D px,")
print("   [rough][cell px][D px]; rough", ROUGH, "cell", CELL, "D", DIAM, "*/")
print("const GRAIN_AP={rough:%s,cell:%s,d:%s,t:%s};" % (ROUGH, CELL, DIAM,
      "[" + ",".join("[" + ",".join("[" + ",".join(f"{v:.5f}" for v in c) + "]" for c in r) + "]" for r in T) + "]"))
