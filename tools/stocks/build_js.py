"""Writes js/03-stocks.js (GENERATED) from tools/stocks/stocks.json: the stock table, measured-grain entries and presets.
    python3 tools/stocks/build_js.py"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
S = json.load(open(os.path.join(HERE, "stocks.json")))
from build_stocks import STOCKS, LO, HI, N
order = [k for k in STOCKS if k in S]
FAM = {"photo": "Measured · photo negative on paper", "cine": "Measured · cinema negative on print", "slide": "Measured · slide & instant", "instant": "Measured · slide & instant", "bw": "Measured · black & white"}
def gsize(iso):   # grain cell size by eye (datasheets don't give clump size): finer for slow stocks
    return 0.9 if iso <= 64 else 1.1 if iso <= 125 else 1.3 if iso <= 250 else 1.55 if iso <= 500 else 1.9
lines = ["/* Ernest Lab · js/03-stocks.js · GENERATED by tools/stocks/build_js.py from tools/stocks/stocks.json. Do not edit by hand.",
         "   Measured film stocks (v1.4): negative + print pairs modelled from datasheets by spectral_film_lut (Jan Lohse, MIT),",
         "   baked into 33³ LUTs (stocks/<key>.lut.gz, loaded when a stock is chosen) over a log2 shaper around 0.18:",
         f"   s = (log2(x/0.18) − ({LO:g})) / {HI-LO:g}. Grain: datasheet RMS granularity as stops of exposure, as in GRAIN_DATA. */",
         '"use strict";', f"const STOCK_LO={LO:g}, STOCK_HI={HI:g}, STOCK_N={N};", "const STOCK_LIB = {"]
for i, k in enumerate(order):
    d = S[k]; gid = 100 + i
    lines.append(f'  {json.dumps(k)}:{{label:{json.dumps(d["label"])},family:{json.dumps(d["family"])},neg:{json.dumps(d["negative"])},print:{json.dumps(d["print"])},'
                 f'gauge:{d["gauge"]},iso:{d["iso"] or 0},year:{d["year"] or 0},bw:{str(d["bw"]).lower()},grain:{gid if d["grain"] else 0},note:{json.dumps(STOCKS[k][5])}}},')
lines.append("};")
lines.append("/* their measured grain, in the GRAIN_DATA form (ids 100+): σ in stops at −6…+4 stops around the stock's mid grey, per layer (capped at 0.35) */")
for i, k in enumerate(order):
    d = S[k]
    if not d["grain"]: continue
    c = [[min(0.35, x) for x in row] for row in d["grain"]]
    lines.append(f'GRAIN_DATA[{100+i}]={{key:{json.dumps(k)},src:{json.dumps(d["negative"])},ei:{d["iso"] or 0},g:{d["gauge"]},mid:{json.dumps(c[6])},c:{json.dumps(c)}}};')
lines.append("/* presets: the stock does tone and colour (neutral film curve and colour), measured grain on its own gauge, physical halation */")
lines.append("const STOCK_PRESETS = {}, STOCK_PRESET_GROUP = {};")
for i, k in enumerate(order):
    d = S[k]; iso = d["iso"] or 100; bw = d["bw"]
    p = {"stock": k, "halPhys": 1, "hal": 0.04 if d["family"] != "photo" else 0.06, "halR": 0.33, "halWarm": 0 if bw else 0.85, "halClip": 2.5,
         "bloom": 0.04, "vig": 0.12}
    if d["grain"]:
        p.update({"gStock": 100 + i, "gGauge": d["gauge"], "grain": 1, "grainSize": gsize(iso), "grainCol": 0 if bw else 0.25, "grainRough": 0.55 if bw else (0.15 if iso <= 100 else 0.3 if iso <= 400 else 0.45),
                  "gSizeG": 1 if bw else 0.92, "gSizeB": 1 if bw else 1.2})
    else:
        p.update({"grain": 0.3, "grainSize": 1.3, "grainCol": 0.25})
    name = d["label"]
    lines.append(f"STOCK_PRESETS[{json.dumps(name)}]={json.dumps(p)}; STOCK_PRESET_GROUP[{json.dumps(name)}]={json.dumps(FAM[d['family']])};")
open(os.path.join(ROOT, "js", "03-stocks.js"), "w").write("\n".join(lines) + "\n")
print("wrote js/03-stocks.js:", len(order), "stocks")
